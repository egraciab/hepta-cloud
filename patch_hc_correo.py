def check_base(base):
    """Verifica que sea realmente el proyecto HEPTA Cloud antes de escribir."""
    faltantes = [p for p in ("backend/server.js", "backend/config/db.js",
                             "backend/middleware/auth.js", "backend/routes")
                 if not (base / p).exists()]
    if faltantes:
        sys.exit(f"ERROR: {base} no parece el proyecto HEPTA Cloud. Falta: {', '.join(faltantes)}")


def mount_routes(server_js, dry_run):
    """Inserta los app.use del correo despues del ultimo app.use('/api..."""
    texto = server_js.read_text()

    if "routes/admin_mail.routes" in texto:
        print("  = server.js ya tiene las rutas de correo montadas")
        return False

    matches = list(re.finditer(r"^.*app\.use\(\s*'/api.*$", texto, re.MULTILINE))
    if not matches:
        print("  ! No encontre ningun app.use('/api...') en server.js — montalo a mano")
        return False

    # Van ANTES del primer app.use('/api...): '/api/admin' es prefijo de
    # '/api/admin/mail', asi que si se montan despues, Express entra primero
    # al router generico y el de correo puede no llegar a ejecutarse nunca.
    corte = matches[0].start()
    nuevo = texto[:corte] + MOUNT_LINES.strip() + "\n\n" + texto[corte:]

    if dry_run:
        print("  [dry-run] insertaria las rutas ANTES de:")
        print("            " + matches[0].group(0).strip())
        return False

    bak = server_js.with_suffix(".js.bak-" + datetime.datetime.now().strftime("%Y%m%d-%H%M%S"))
    bak.write_text(texto)
    server_js.write_text(nuevo)
    print(f"  + rutas montadas en server.js (respaldo: {bak.name})")
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="/opt/heptacloud", help="raiz del proyecto (default /opt/heptacloud)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--mount", action="store_true", help="tambien inserta los app.use en backend/server.js")
    args = ap.parse_args()

    base = pathlib.Path(args.base).expanduser().resolve()
    if not base.is_dir():
        sys.exit(f"ERROR: {base} no existe")
    check_base(base)

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    escritos, respaldos = [], []

    for rel, b64 in FILES.items():
        target = base / rel
        contenido = base64.b64decode("".join(b64.split()))

        if args.dry_run:
            estado = "sobrescribiria" if target.exists() else "crearia"
            print(f"  [dry-run] {estado} {rel}")
            continue

        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            if target.read_bytes() == contenido:
                print(f"  = sin cambios  {rel}")
                continue
            bak = target.with_suffix(target.suffix + f".bak-{stamp}")
            bak.write_bytes(target.read_bytes())
            respaldos.append(bak.name)
        target.write_bytes(contenido)
        target.chmod(0o755 if "/scripts/" in rel else 0o644)
        escritos.append(rel)
        print(f"  + {rel}")

    if args.mount or args.dry_run:
        mount_routes(base / "backend" / "server.js", args.dry_run)

    if args.dry_run:
        print("\n(dry-run: no se escribio nada)")
        return

    print(f"\n{len(escritos)} archivo(s) escrito(s), {len(respaldos)} respaldo(s).")
    print("\n" + "=" * 72)
    print("PASO 1 — agregar al .env de /opt/heptacloud:")
    print(ENV_SNIPPET)
    print("PASO 2 — migracion (Postgres corre en el host):")
    print(f"    psql -U <usuario> -d <base> -f {base}/sql/migrate_s19_correo.sql\n")
    if not args.mount:
        print("PASO 3 — montar las rutas en backend/server.js:")
        print(MOUNT_LINES)
    else:
        print("PASO 3 — rutas ya montadas en server.js\n")
    print("PASO 4 — rebuild (tu Dockerfile COPIA el backend, no alcanza restart):")
    print("    cd /opt/heptacloud && docker compose up -d --build backend")
    print("    docker compose logs -f --tail=50 backend\n")
    print("PASO 5 — probar:")
    print("    docker compose exec backend node -e \"console.log('fetch:', typeof fetch)\"")
    print("    curl -s -H \"Authorization: Bearer <token-admin>\" \\")
    print("      http://localhost:3100/api/admin/mail/health | head")
    print("=" * 72)


if __name__ == "__main__":
    main()
